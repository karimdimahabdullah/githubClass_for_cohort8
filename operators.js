
// Arithmetic Operators
let x = 50
let y = 5

console.log(x + y) // Addition
console.log(x - y) // Subtraction
console.log(x * y) // Multiplication
console.log(x / y) // Division
console.log(x % y) // Modulus (Remainder)

//Comparison operators
let a = 10;
let b = 20;
console.log(a === b); // false
console.log(a !== b); // true
console.log(a > b); // false
console.log(a < b); // true
console.log(a >= b); // false
console.log(a <= b); // true

//Logical Operators
let isAdult = true;
let hadID = false;

console.log(isAdult && hadID); // false (AND)
console.log(isAdult || hadID); // true (OR)
console.log(!isAdult); // false (NOT)

// Assignment Operators
let t = 20;
console.log(t += 5); // 25 (Addition assignment)
console.log(t -= 10); // 15 (Subtraction assignment) 
console.log(t *= 2); // 30 (Multiplication assignment)
console.log(t /= 2); // 15 (Division assignment)   
console.log(t %= 2); // 1 (Modulus assignment)

